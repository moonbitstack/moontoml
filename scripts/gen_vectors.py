"""Write the toml-test corpus into this package as MoonBit source.

`toml-test` publishes one document per case, with the tree it denotes beside it.
Both directions of the library are checked against that corpus, and the corpus is
read at run time from this file rather than from disk, so the tests run on every
backend.

Usage, from the repository root:

    python scripts/gen_vectors.py

The version is pinned and the archive is checked against its digest, so the
generated files change only when the pin does. CI reruns this and fails if the
result differs from what is committed.
"""
import hashlib
import io
import pathlib
import subprocess
import tarfile
import urllib.request

PIN = "v2.2.0"
DIGEST = "fdab2779b3902eb08030f389a5d53e95c5b49404149ac6f2eda5227a5363c232"
ARCHIVE = f"https://codeload.github.com/toml-lang/toml-test/tar.gz/refs/tags/{PIN}"
LISTS = {
    "": "tests/files-toml-1.0.0",
    "_11": "tests/files-toml-1.1.0",
}

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "conformance"
CACHE = pathlib.Path.home() / ".cache" / "moontoml" / f"toml-test-{PIN}.tar.gz"

HEADER = """\
// Copyright 2026 Leo Cheng
// SPDX-License-Identifier: Apache-2.0

// Generated by scripts/gen_vectors.py from toml-test {pin}. Do not edit.
"""


def fetch():
    if CACHE.exists() and digest(CACHE.read_bytes()) == DIGEST:
        return CACHE.read_bytes()
    with urllib.request.urlopen(ARCHIVE, timeout=60) as reply:
        data = reply.read()
    if digest(data) != DIGEST:
        raise SystemExit(f"toml-test {PIN}: the archive does not match its digest")
    CACHE.parent.mkdir(parents=True, exist_ok=True)
    CACHE.write_bytes(data)
    return data


def digest(data):
    return hashlib.sha256(data).hexdigest()


def corpora():
    """Each edition's file list and the files it names, keyed by path under `tests/`.

    The keys are the suffix the generated files carry: ``""`` for 1.0.0 and
    ``"_11"`` for 1.1.0, which is the edition that list was cut for.
    """
    with tarfile.open(fileobj=io.BytesIO(fetch())) as tar:
        root = tar.getnames()[0].split("/")[0]
        files = {}
        for member in tar.getmembers():
            if not member.isfile():
                continue
            name = member.name[len(root) + 1 :]
            files[name] = tar.extractfile(member).read()
    out = {}
    for suffix, list_path in LISTS.items():
        names = files[list_path].decode().split()
        out[suffix] = {name: files["tests/" + name] for name in names}
    return out


def text(value):
    """A MoonBit string literal for this text, escaping everything outside ASCII."""
    out = ['"']
    for char in value:
        if char == "\\":
            out.append("\\\\")
        elif char == '"':
            out.append('\\"')
        elif char == "\n":
            out.append("\\n")
        elif char == "\r":
            out.append("\\r")
        elif char == "\t":
            out.append("\\t")
        elif 0x20 <= ord(char) < 0x7F:
            out.append(char)
        else:
            out.append("\\u{%x}" % ord(char))
    out.append('"')
    return "".join(out)


def blob(value):
    """A MoonBit bytes literal that stands for these bytes exactly."""
    out = ['b"']
    for byte in value:
        if byte == 0x5C:
            out.append("\\\\")
        elif byte == 0x22:
            out.append('\\"')
        elif 0x20 <= byte < 0x7F:
            out.append(chr(byte))
        else:
            out.append("\\x%02x" % byte)
    out.append('"')
    return "".join(out)


def chunk(items, size):
    return [items[i : i + size] for i in range(0, len(items), size)]


def accepted(files, suffix):
    cases = [
        (name, files[name], files[name[:-5] + ".json"])
        for name in sorted(files)
        if name.startswith("valid/") and name.endswith(".toml")
    ]
    body = [HEADER.format(pin=PIN)]
    names = []
    for number, part in enumerate(chunk(cases, 20)):
        names.append(f"accepted{suffix}_{number:02d}")
        body.append("///|")
        body.append(f"fn accepted{suffix}_{number:02d}() -> Array[Accepted] {{")
        body.append("  [")
        for name, src, want in part:
            body.append("    {")
            body.append(f"      name: {text(name)},")
            body.append(f"      src: {blob(src)},")
            body.append(f"      want: {text(want.decode())},")
            body.append("    },")
        body.append("  ]")
        body.append("}")
        body.append("")
    body.append("///|")
    body.append(f"pub fn accepted{suffix}() -> Array[Accepted] {{")
    body.append("  let all : Array[Accepted] = []")
    for name in names:
        body.append(f"  all.append({name}())")
    body.append("  all")
    body.append("}")
    body.append("")
    return "\n".join(body)


def rejected(files, suffix):
    cases = [
        (name, files[name])
        for name in sorted(files)
        if name.startswith("invalid/") and name.endswith(".toml")
    ]
    body = [HEADER.format(pin=PIN)]
    names = []
    for number, part in enumerate(chunk(cases, 50)):
        names.append(f"rejected{suffix}_{number:02d}")
        body.append("///|")
        body.append(f"fn rejected{suffix}_{number:02d}() -> Array[Rejected] {{")
        body.append("  [")
        for name, src in part:
            body.append("    {")
            body.append(f"      name: {text(name)},")
            body.append(f"      src: {blob(src)},")
            body.append("    },")
        body.append("  ]")
        body.append("}")
        body.append("")
    body.append("///|")
    body.append(f"pub fn rejected{suffix}() -> Array[Rejected] {{")
    body.append("  let all : Array[Rejected] = []")
    for name in names:
        body.append(f"  all.append({name}())")
    body.append("  all")
    body.append("}")
    body.append("")
    return "\n".join(body)


def main():
    per_edition = corpora()
    written = {}
    for suffix, files in per_edition.items():
        written[f"vectors_accepted{suffix}.mbt"] = accepted(files, suffix)
        written[f"vectors_rejected{suffix}.mbt"] = rejected(files, suffix)
    for name, content in written.items():
        (OUT / name).write_bytes(content.encode("utf-8"))
        print(f"wrote src/conformance/{name}")
    # What is written is not what the formatter leaves; running it here keeps the
    # repository clean after one command, and keeps the check in CI a plain diff.
    subprocess.run(["moon", "fmt"], cwd=ROOT, check=True)


if __name__ == "__main__":
    main()
